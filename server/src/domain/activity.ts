/** The type is necessary but not sufficient: automated notes and system writes are bookkeeping. */
export const isWorkEvent = (type: EventType, actor: string, from?: string | null): boolean =>
  actor !== 'system' && WORK_EVENT[type] && !(type === 'owner_note.added' && from === 'radar');

const WORK_TYPES = (Object.entries(WORK_EVENT) as [EventType, boolean][])
  .filter(([, work]) => work)
  .map(([type]) => `'${type}'`)
  .join(', ');

/** A SQL predicate for a row from events, with a caller-chosen safe alias. */
export const workEventSql = (alias: 'e' | 'events') =>
  `${alias}.actor_kind <> 'system' AND ${alias}.type IN (${WORK_TYPES}) AND NOT (${alias}.type = 'owner_note.added' AND coalesce(json_extract(${alias}.data, '$.from'), '') = 'radar')`;
